#!/usr/bin/env bash
#
# Project rules that a linter can't enforce, checked in CI before anything
# else runs — see TECHNICAL.md § The gates. Extend this file rather than
# writing the same rule as a comment: a rule that only lives in prose gets
# broken by the first change that doesn't re-read it.
#
# Every search is scoped to the directories being policed — never to
# scripts/ — because this file necessarily contains the strings it looks for.
#
# Every run also appends one line to .claude/logs/gates.jsonl: which checks
# passed or failed, when, on which commit. That file is gitignored — it
# never leaves this machine — but it's the closest thing this template has
# to telemetry, and it's local by construction rather than by policy. See
# AGENTS.md § Self-improving: closing the loop for what it's for: a check
# that has never once failed across months of sessions is a candidate to
# retire; a rule you keep explaining in review instead of finding here is a
# candidate to add.

set -uo pipefail

cd "$(dirname "$0")/.."

status=0
checks=()

fail() {
	status=1
	checks+=("{\"name\":\"$3\",\"pass\":false}")
	printf '  FAIL  %s\n' "$1"
	printf '%s\n' "$2" | sed 's/^/        /'
}

pass() {
	checks+=("{\"name\":\"$2\",\"pass\":true}")
	printf '    ok  %s\n' "$1"
}

# ── 1. No route from a string to markup or script ────────────────────────────
# Svelte escapes interpolated text by default; nothing in a fresh project
# should ever need to bypass that.
sinks=$(grep -rnF \
	-e '{@html' \
	-e 'innerHTML' \
	-e 'outerHTML' \
	-e 'insertAdjacentHTML' \
	-e 'eval(' \
	-e 'new Function(' \
	-e 'document.write' \
	src 2>/dev/null)

if [ -n "$sinks" ]; then
	fail "markup/script sink in src/" "$sinks" "no-injection-sinks"
else
	pass "no markup or script sinks in src/" "no-injection-sinks"
fi

# ── 2. No secret-shaped name is exposed to the browser ───────────────────────
# $env/static/public and any PUBLIC_ variable are inlined into the client
# bundle. A name that reads as a token, secret or key is a shipped secret the
# moment someone adds it, however it's meant to be used.
public=$(grep -rnE 'PUBLIC_[A-Z0-9_]*(TOKEN|SECRET|KEY)' \
	src .github vercel.json 2>/dev/null)

if [ -n "$public" ]; then
	fail "PUBLIC_ variable name looks like a secret" "$public" "no-secret-shaped-public-vars"
else
	pass "no secret-shaped PUBLIC_ names" "no-secret-shaped-public-vars"
fi

# ── 3. The baseline security headers are still in vercel.json ───────────────
# A generic edit to vercel.json (adding a rewrite, a cron, a redirect) is an
# easy place to lose the headers block entirely rather than extend it.
#
# Content-Security-Policy is in this list for a specific reason: the app's
# real CSP is generated by SvelteKit into a <meta> tag, but `frame-ancestors`
# is ignored there by specification and is dropped from the tag, so the only
# thing actually refusing to be framed is this header (plus X-Frame-Options).
# Lose it and the docs would still claim the protection. See TECHNICAL.md
# § Security headers.
required_headers='Strict-Transport-Security X-Content-Type-Options X-Frame-Options Content-Security-Policy'
missing=""
for header in $required_headers; do
	grep -q "\"$header\"" vercel.json 2>/dev/null || missing="$missing $header"
done

if [ -n "$missing" ]; then
	fail "vercel.json is missing baseline security headers" "$(echo "$missing" | xargs)" "security-headers-present"
else
	pass "baseline security headers present in vercel.json" "security-headers-present"
fi

# ── 4. The instructions stay short ───────────────────────────────────────────
# AGENTS.md (portable) and STACK.md (the stack) are both read in full every
# session, and the argument for keeping them apart from CLAUDE.md in the first
# place was that a bloated instructions file gets skimmed rather than followed
# (docs/PATTERNS.md § Instructions file). That argument was worth exactly
# nothing while the only thing enforcing it was the sentence at the top of the
# file saying so — this repo grew it by 25% in one session without noticing.
#
# So it's a budget, in the same spirit as osseus's JavaScript budget: raise it
# deliberately, in the commit that earns it, or move the detail into
# TECHNICAL.md or docs/ where nobody pays for it per turn. It counts the two
# files together, because splitting one file in two is not a way to make it
# shorter. 280 for AGENTS.md alone became 310 for both when the split landed
# and brought the portable/stack layering and seven new rules with it.
# Overridable so the failure path is testable without editing this file:
# `AGENTS_MAX=10 pnpm run gates` should fail.
AGENTS_MAX="${AGENTS_MAX:-310}"
instructions="AGENTS.md STACK.md"

# Counted only if every file can actually be read. A gate that passes when it
# couldn't do its job is worse than no gate — found the hard way when a
# mis-scoped test run made AGENTS.md unreadable and this reported "ok".
unreadable=""
for f in $instructions; do
	[ -r "$f" ] || unreadable="$unreadable $f"
done

if [ -n "$unreadable" ]; then
	fail "instructions missing or unreadable:$unreadable" \
		"the instructions are the one thing this project cannot work without" \
		"instructions-file-budget"
else
	# shellcheck disable=SC2086 # word-splitting the list is the point
	agents_lines=$(cat $instructions | wc -l | tr -d ' ')
	if [ "$agents_lines" -gt "$AGENTS_MAX" ]; then
		fail "AGENTS.md + STACK.md are $agents_lines lines (budget $AGENTS_MAX)" \
			"move detail into TECHNICAL.md or docs/, or raise AGENTS_MAX on purpose" \
			"instructions-file-budget"
	else
		pass "AGENTS.md + STACK.md are $agents_lines lines (budget $AGENTS_MAX)" "instructions-file-budget"
	fi
fi

# ── 5. The changelog heads with the version being shipped ────────────────────
# package.json is the only place the version is written (vite.config.ts
# injects it; pnpm-lock.yaml doesn't record the root package's version), so
# the copy that can drift is CHANGELOG.md's top heading — and that one ships,
# because the app bundles the file for its "What's new" dialog. See
# TECHNICAL.md § Versioning and the changelog.
#
# The heading shape is src/lib/changelog.ts's HEADING, byte for byte: version,
# a space, an em dash, en dash or hyphen, a space, an ISO date. Every `## `
# heading must have it, because a heading the parser can't read isn't an
# error there — it's a release the dialog silently never shows.
CHANGELOG="${CHANGELOG:-CHANGELOG.md}"
heading_re='^## ([0-9]+\.[0-9]+\.[0-9]+) (—|–|-) ([0-9]{4}-[0-9]{2}-[0-9]{2})[[:space:]]*$'
version=$(node -p 'require("./package.json").version' 2>/dev/null)

if [ -z "$version" ]; then
	fail "could not read the version from package.json" "" "changelog-heads-with-version"
elif [ ! -r "$CHANGELOG" ]; then
	fail "$CHANGELOG is missing or unreadable" \
		"it is bundled into the app — create it with a '## $version — $(date -u +%Y-%m-%d)' section" \
		"changelog-heads-with-version"
else
	malformed=$(grep -n '^## ' "$CHANGELOG" | grep -vE "^[0-9]+:${heading_re#^}")
	top=$(sed -nE "s/${heading_re}/\1/p" "$CHANGELOG" | head -n 1)
	want="## $version — $(date -u +%Y-%m-%d)"
	if [ -n "$malformed" ]; then
		fail "$CHANGELOG has a heading the app can't read" \
			"$malformed
headings are '## X.Y.Z — YYYY-MM-DD'" "changelog-heads-with-version"
	elif [ "$top" != "$version" ]; then
		# Say which fix it is: a patch renames its minor's heading, a minor adds one.
		if [ -n "$top" ] && [ "${top%.*}" = "${version%.*}" ]; then
			todo="rewrite '## $top …' as '$want' and add this patch's lines under it"
		else
			todo="start a section headed '$want' above it"
		fi
		fail "$CHANGELOG does not open with $version" \
			"top heading is '${top:-none}' — $todo" "changelog-heads-with-version"
	else
		pass "$CHANGELOG opens with $version" "changelog-heads-with-version"
	fi
fi

# ── 6. Each release is short, and plain ──────────────────────────────────────
# Three lines is the usual release, six the most: a note that fills a screen
# doesn't get read to the end. Non-blank lines are counted, so where a bullet
# wraps is the writer's business. Overridable to test the failure path:
# `CHANGELOG_MAX=1 pnpm run gates` should fail.
#
# And no markup the dialog can't show — it renders text and `code` spans,
# nothing else, so bold, links or a nested heading would appear as their raw
# characters. The preamble above the first release is for people reading the
# file and is exempt from both.
CHANGELOG_MAX="${CHANGELOG_MAX:-6}"

if [ -r "$CHANGELOG" ]; then
	long=$(awk -v max="$CHANGELOG_MAX" '
		/^## / { if (name != "" && len > max) printf "%s — %d lines\n", name, len; name = $0; len = 0; next }
		name != "" && $0 !~ /^[[:space:]]*$/ { len++ }
		END { if (name != "" && len > max) printf "%s — %d lines\n", name, len }
	' "$CHANGELOG")
	markup=$(awk '
		/^## / { r = 1; next }
		r && (/\*\*/ || /\[[^]]*\]\(/ || /^[[:space:]]*#/) { printf "%d: %s\n", NR, $0 }
	' "$CHANGELOG")
	if [ -n "$long" ]; then
		fail "a release in $CHANGELOG is over $CHANGELOG_MAX lines" \
			"$long
cut it to what a user needs to know, or raise CHANGELOG_MAX on purpose" "changelog-releases-short-and-plain"
	elif [ -n "$markup" ]; then
		fail "$CHANGELOG has markup the app shows as raw characters" \
			"$markup
plain text and \`code\` spans only" "changelog-releases-short-and-plain"
	else
		pass "every release is $CHANGELOG_MAX lines or fewer, plain text" "changelog-releases-short-and-plain"
	fi
else
	fail "$CHANGELOG is missing or unreadable" "see the check above" "changelog-releases-short-and-plain"
fi

# ── local, gitignored log — see the header comment ───────────────────────────
mkdir -p .claude/logs
ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)
sha=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
joined=$(IFS=,; echo "${checks[*]}")
overall=$([ "$status" -eq 0 ] && echo pass || echo fail)
printf '{"ts":"%s","sha":"%s","status":"%s","checks":[%s]}\n' "$ts" "$sha" "$overall" "$joined" \
	>> .claude/logs/gates.jsonl

if [ "$status" -ne 0 ]; then
	printf '\ngates failed\n'
fi

exit "$status"
